#!/usr/bin/env python3
"""Write a module of literal item lists (point masks of t-subsets of range v), each proved equal to
`itemsList v t` by the kernel. Usage: emit_items.py Module v:t [v:t ...]  (e.g. Veles/Items)"""
import sys
out = ["import Veles.CertKit\n", "/-! Generated by `certgen/emit_items.py`. Do not edit. -/\n",
       "namespace Veles.CertKit\n"]
mod = sys.argv[1]
out.insert(1, "set_option maxRecDepth 200000\nset_option maxHeartbeats 0\n")
for arg in sys.argv[2:]:
    v, t = map(int, arg.split(":"))
    L = [m for m in range(1 << v) if bin(m).count("1") == t]
    out.append(f"/-- The {len(L)} point masks of the {t}-subsets of `range {v}`. -/\n"
               f"def items{v}_{t} : List ℕ := [{', '.join(map(str, L))}]\n\n"
               f"set_option maxRecDepth 100000 in\n"
               f"theorem items{v}_{t}_eq : items{v}_{t} = itemsList {v} {t} := by decide +kernel\n\n"
               f"theorem items{v}_{t}_good : ItemsGood {v} {t} items{v}_{t} := itemsGood_of_eq items{v}_{t}_eq\n\n")
out.append("end Veles.CertKit\n")
open(mod + ".lean", "w").write("".join(out))
